"""Component [J]: The Evidence Check for RegImpact-SL.

Verifies that narrative summaries generated by the LLM Explanation Layer [I]
are strictly grounded in the structured facts and official quote spans of the
StructuredImpactReport, preventing hallucinated thresholds, fines, or dates.
"""

from datetime import date
import re
from typing import Any, Dict, List, Optional, Set, Tuple

from pydantic import BaseModel, ConfigDict

from backend.src.engine.applicability import parse_date


class EvidenceCheckResult(BaseModel):
    """Detailed diagnostic report of evidence verification."""

    model_config = ConfigDict(extra="allow")
    is_valid: bool
    ungrounded_numbers: List[float] = []
    ungrounded_dates: List[str] = []
    message: Optional[str] = None


class EvidenceError(Exception):
    """Raised when an ungrounded claim is detected in the explanation summary."""

    pass


class EvidenceChecker:
    """Deterministic evidence gatekeeper validating claims in narrative summaries."""

    def __init__(self, strict_raise: bool = False):
        self.strict_raise = strict_raise

    def collect_grounded_data(self, report: Any) -> Tuple[Set[float], Set[date]]:
        """Extract all valid numbers and dates present across the entire StructuredImpactReport."""
        grounded_numbers: Set[float] = set()
        grounded_dates: Set[date] = set()

        def add_numbers_from_text(t: Optional[str]) -> None:
            if not t:
                return
            # Remove comma separators inside numbers (e.g., 50,000 -> 50000)
            cleaned = re.sub(r"(\d+),(\d+)", r"\1\2", str(t))
            matches = re.findall(r"(?<![a-zA-Z0-9_\.])\d+(?:\.\d+)?(?![a-zA-Z0-9_\.])", cleaned)
            for m in matches:
                try:
                    grounded_numbers.add(float(m))
                except ValueError:
                    pass

        def add_date_from_val(val: Any) -> None:
            if not val:
                return
            if isinstance(val, (date, str)):
                d = parse_date(val)
                if d:
                    grounded_dates.add(d)
                    grounded_numbers.add(float(d.year))
                    grounded_numbers.add(float(d.month))
                    grounded_numbers.add(float(d.day))

        # 1. Report-level metadata
        as_at = getattr(report, "as_at_date", None)
        if as_at:
            add_date_from_val(as_at)
            add_numbers_from_text(as_at)

        for count_attr in (
            "total_rules_evaluated",
            "applicable_rules_count",
            "conditional_rules_count",
            "not_applicable_rules_count",
            "unsupported_rules_count",
        ):
            val = getattr(report, count_attr, None)
            if val is not None and isinstance(val, (int, float)):
                grounded_numbers.add(float(val))

        for text_list_attr in (
            "action_checklist",
            "affected_activities",
            "affected_documents",
            "missing_fields",
            "clarifying_questions",
        ):
            items = getattr(report, text_list_attr, []) or []
            for item in items:
                add_numbers_from_text(str(item))

        # 2. Rule evaluation details
        evals = getattr(report, "evaluations", []) or []
        for ev in evals:
            # Rule identifiers and provenance
            for attr in ("rule_id", "clause", "instrument", "authority", "reason", "temporal_status"):
                txt = getattr(ev, attr, None) if not isinstance(ev, dict) else ev.get(attr)
                if txt:
                    add_numbers_from_text(str(txt))
                    add_date_from_val(txt)

            # Quote span
            quote = getattr(ev, "quote_span", None) if not isinstance(ev, dict) else ev.get("quote_span")
            if quote:
                add_numbers_from_text(quote)
                # Find all potential dates inside quote span
                iso_dates = re.findall(r"\b\d{4}-\d{2}-\d{2}\b", quote)
                for d_str in iso_dates:
                    add_date_from_val(d_str)

            # Missing fields & counterfactuals
            cfs = getattr(ev, "counterfactuals", []) if not isinstance(ev, dict) else ev.get("counterfactuals", [])
            for cf in cfs or []:
                add_numbers_from_text(cf)

            mfs = getattr(ev, "missing_fields", []) if not isinstance(ev, dict) else ev.get("missing_fields", [])
            for mf in mfs or []:
                add_numbers_from_text(mf)

            # Evaluation trace values (target values and observed values)
            trace = getattr(ev, "evaluation_trace", []) if not isinstance(ev, dict) else ev.get("evaluation_trace", [])
            for t_entry in trace or []:
                if isinstance(t_entry, dict):
                    add_numbers_from_text(str(t_entry.get("target_value", "")))
                    add_numbers_from_text(str(t_entry.get("observed_value", "")))
                    add_numbers_from_text(str(t_entry.get("field", "")))
                    if isinstance(t_entry.get("target_value"), (int, float)):
                        grounded_numbers.add(float(t_entry["target_value"]))
                    if isinstance(t_entry.get("observed_value"), (int, float)):
                        grounded_numbers.add(float(t_entry["observed_value"]))

            # Impact details
            impact = getattr(ev, "impact", None) if not isinstance(ev, dict) else ev.get("impact")
            if impact:
                if isinstance(impact, dict):
                    for act in impact.get("action_items", []):
                        add_numbers_from_text(act)
                    for a in impact.get("affected_activities", []):
                        add_numbers_from_text(a)
                    for d in impact.get("affected_documents", []):
                        add_numbers_from_text(d)
                    if impact.get("timeline_note"):
                        add_numbers_from_text(impact["timeline_note"])
                        add_date_from_val(impact["timeline_note"])
                else:
                    for act in getattr(impact, "action_items", []):
                        add_numbers_from_text(act)
                    for a in getattr(impact, "affected_activities", []):
                        add_numbers_from_text(a)
                    for d in getattr(impact, "affected_documents", []):
                        add_numbers_from_text(d)
                    if getattr(impact, "timeline_note", None):
                        add_numbers_from_text(impact.timeline_note)
                        add_date_from_val(impact.timeline_note)

        return grounded_numbers, grounded_dates

    def extract_dates(self, text: str) -> List[Tuple[date, str]]:
        """Extract explicit calendar dates from natural language text."""
        found_dates: List[Tuple[date, str]] = []

        # 1. ISO format: YYYY-MM-DD
        for m in re.finditer(r"\b\d{4}-\d{2}-\d{2}\b", text):
            d = parse_date(m.group(0))
            if d:
                found_dates.append((d, m.group(0)))

        # 2. Commonwealth / natural textual dates (e.g. 1st June 2024, June 1, 2024)
        textual_pattern = (
            r"\b(?:\d{1,2}(?:st|nd|rd|th)?\s+(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{4})"
            r"|(?:\b(?:January|February|March|April|May|June|July|August|September|October|November|December)\s+\d{1,2}(?:st|nd|rd|th)?(?:,)?\s+\d{4})"
        )
        for m in re.finditer(textual_pattern, text, re.IGNORECASE):
            d = parse_date(m.group(0))
            if d:
                found_dates.append((d, m.group(0)))

        return found_dates

    def extract_numbers(self, text: str, excluded_spans: Optional[List[str]] = None) -> List[float]:
        """Extract all numeric quantities from text, excluding known date substrings."""
        scrubbed = text
        if excluded_spans:
            for span in excluded_spans:
                scrubbed = scrubbed.replace(span, " ")

        # Normalize thousands comma separators (50,000 -> 50000)
        cleaned = re.sub(r"(\d+),(\d+)", r"\1\2", scrubbed)
        matches = re.findall(r"(?<![a-zA-Z0-9_\.])\d+(?:\.\d+)?(?![a-zA-Z0-9_\.])", cleaned)

        numbers: List[float] = []
        for m in matches:
            try:
                numbers.append(float(m))
            except ValueError:
                pass
        return numbers

    def check_claims(self, summary_text: str, report: Any) -> EvidenceCheckResult:
        """Perform granular grounding check and return detailed diagnostics."""
        if not summary_text or not summary_text.strip():
            return EvidenceCheckResult(is_valid=True)

        grounded_numbers, grounded_dates = self.collect_grounded_data(report)

        # 1. Date Grounding Check
        found_dates = self.extract_dates(summary_text)
        ungrounded_dates: List[str] = []
        date_spans: List[str] = []

        for d_obj, d_raw in found_dates:
            date_spans.append(d_raw)
            if d_obj not in grounded_dates:
                ungrounded_dates.append(d_raw)

        # 2. Number Grounding Check
        found_numbers = self.extract_numbers(summary_text, excluded_spans=date_spans)
        ungrounded_numbers: List[float] = []

        for num in found_numbers:
            # Check if number exists in grounded_numbers
            if num not in grounded_numbers:
                ungrounded_numbers.append(num)

        is_valid = (len(ungrounded_dates) == 0) and (len(ungrounded_numbers) == 0)
        message = None
        if not is_valid:
            parts = []
            if ungrounded_numbers:
                parts.append(f"Ungrounded numbers detected: {ungrounded_numbers}")
            if ungrounded_dates:
                parts.append(f"Ungrounded dates detected: {ungrounded_dates}")
            message = "; ".join(parts)

        return EvidenceCheckResult(
            is_valid=is_valid,
            ungrounded_numbers=ungrounded_numbers,
            ungrounded_dates=ungrounded_dates,
            message=message,
        )

    def verify_claims(self, summary_text: str, report: Any) -> bool:
        """Assert that every number and date in summary_text exists in the report.
        
        Returns:
            True if all claims are grounded, False if hallucinated numbers or dates are found.
        """
        result = self.check_claims(summary_text, report)
        if not result.is_valid and self.strict_raise:
            raise EvidenceError(f"Evidence verification failed: {result.message}")
        return result.is_valid
